CREATE SCHEMA WILDFIRE;

CREATE TABLE WILDFIRE.TRACTS (
  TRACT_ID CHAR(11) NOT NULL PRIMARY KEY, COUNTY VARCHAR(40), LAT DOUBLE, LON DOUBLE,
  VEGETATION DOUBLE, SLOPE DOUBLE, ELEVATION DOUBLE, DROUGHT_BASE DOUBLE, WIND_BASE DOUBLE,
  MEDIAN_INCOME DOUBLE, INCOME_Q SMALLINT, HOME_VALUE DOUBLE, RENTER_SHARE DOUBLE, PCT_MINORITY DOUBLE, SVI DOUBLE
);
CREATE TABLE WILDFIRE.POLICIES (
  POLICY_ID BIGINT NOT NULL PRIMARY KEY, TRACT_ID CHAR(11) NOT NULL, PREMIUM DECIMAL(10,2),
  HOME_AGE DOUBLE, MITIGATION_SCORE DOUBLE, NON_RENEWAL_FLAG SMALLINT, DENIAL_FLAG SMALLINT
);
CREATE INDEX WILDFIRE.IX_POL_TRACT ON WILDFIRE.POLICIES (TRACT_ID);
CREATE TABLE WILDFIRE.TRACT_SCORES (
  TRACT_ID CHAR(11) NOT NULL PRIMARY KEY, RISK_PROB DOUBLE, RISK_UNCERTAINTY DOUBLE, RISK_SCORE DOUBLE, RISK_TIER VARCHAR(10)
);
CREATE TABLE WILDFIRE.TRACT_GAPS (
  TRACT_ID CHAR(11) NOT NULL PRIMARY KEY, N_POLICIES INTEGER, AVG_PREMIUM DOUBLE, EXPECTED_PREMIUM DOUBLE,
  PREMIUM_GAP_PCT DOUBLE, NR_RATE DOUBLE, NR_GAP_PP DOUBLE, DENIAL_RATE DOUBLE
);
