CREATE TABLE WILDFIRE.TRACTS (
  TRACT_ID VARCHAR(16) NOT NULL PRIMARY KEY, COUNTY VARCHAR(40),
  LAT DECIMAL(9,6), LON DECIMAL(9,6),
  VEGETATION DOUBLE, SLOPE DOUBLE, ELEVATION DOUBLE, WUI_PROXIMITY DOUBLE,
  DROUGHT_BASE DOUBLE, WIND_BASE DOUBLE,
  MEDIAN_INCOME DOUBLE, MEDIAN_HOME_VALUE DOUBLE, PCT_MINORITY DOUBLE, RENTER_SHARE DOUBLE, SVI DOUBLE,
  INCOME_QUINTILE SMALLINT, IS_PLACEHOLDER SMALLINT
);
CREATE TABLE WILDFIRE.TRACT_YEAR (
  TRACT_ID VARCHAR(16) NOT NULL, YEAR SMALLINT NOT NULL,
  DROUGHT_INDEX DOUBLE, WIND_SPEED DOUBLE, TEMP_ANOMALY DOUBLE, FIRES_PRIOR5 SMALLINT, BURNED SMALLINT,
  VEGETATION DOUBLE, SLOPE DOUBLE, ELEVATION DOUBLE, WUI_PROXIMITY DOUBLE,
  PRIMARY KEY (TRACT_ID, YEAR)
);
CREATE TABLE WILDFIRE.POLICIES (
  POLICY_ID INTEGER NOT NULL PRIMARY KEY, TRACT_ID VARCHAR(16) NOT NULL,
  PREMIUM DECIMAL(12,2), COVERAGE DECIMAL(14,0), HOME_AGE DOUBLE, MITIGATION_SCORE DOUBLE,
  NON_RENEWAL_FLAG SMALLINT, DENIAL_FLAG SMALLINT
);
CREATE INDEX WILDFIRE.IX_POL_TRACT ON WILDFIRE.POLICIES (TRACT_ID);
CREATE TABLE WILDFIRE.RISK_SCORES (
  TRACT_ID VARCHAR(16) NOT NULL PRIMARY KEY, RISK_SCORE DOUBLE, RISK_UNCERTAINTY DOUBLE,
  RISK_LO DOUBLE, RISK_HI DOUBLE, RISK_PERCENTILE DOUBLE, RISK_LOGIT_Z DOUBLE
);

-- Sample in-place queries (data never leaves the platform; only aggregates are exported)
-- 1) Non-renewal rate by income quintile
SELECT T.INCOME_QUINTILE, COUNT(*) AS POLICIES, AVG(CAST(P.NON_RENEWAL_FLAG AS DOUBLE)) AS NONRENEWAL_RATE
  FROM WILDFIRE.POLICIES P JOIN WILDFIRE.TRACTS T ON T.TRACT_ID = P.TRACT_ID
 GROUP BY T.INCOME_QUINTILE ORDER BY T.INCOME_QUINTILE;
-- 2) Average premium rate vs modeled risk, by tract
SELECT R.TRACT_ID, R.RISK_SCORE, AVG(P.PREMIUM / P.COVERAGE * 1000) AS RATE_PER_1000
  FROM WILDFIRE.POLICIES P JOIN WILDFIRE.RISK_SCORES R ON R.TRACT_ID = P.TRACT_ID
 GROUP BY R.TRACT_ID, R.RISK_SCORE;
