-- Sample in-place analytics on Db2 for z/OS: data never leaves the platform.
-- 1) Non-renewal rate by income quintile (raw)
SELECT T.INCOME_Q, COUNT(*) AS POLICIES, AVG(CAST(P.NON_RENEWAL_FLAG AS DOUBLE)) AS NR_RATE, AVG(P.PREMIUM) AS AVG_PREMIUM
FROM WILDFIRE.POLICIES P JOIN WILDFIRE.TRACTS T ON T.TRACT_ID = P.TRACT_ID
GROUP BY T.INCOME_Q ORDER BY T.INCOME_Q;

-- 2) Within the SAME risk tier, how do income quintiles compare?
SELECT S.RISK_TIER, T.INCOME_Q, AVG(P.PREMIUM) AS AVG_PREMIUM, AVG(CAST(P.NON_RENEWAL_FLAG AS DOUBLE)) AS NR_RATE
FROM WILDFIRE.POLICIES P
JOIN WILDFIRE.TRACTS T ON T.TRACT_ID = P.TRACT_ID
JOIN WILDFIRE.TRACT_SCORES S ON S.TRACT_ID = P.TRACT_ID
GROUP BY S.RISK_TIER, T.INCOME_Q ORDER BY S.RISK_TIER, T.INCOME_Q;

-- 3) Tracts with the largest unexplained premium gap (min. 60 policies)
SELECT TRACT_ID, N_POLICIES, AVG_PREMIUM, EXPECTED_PREMIUM, PREMIUM_GAP_PCT
FROM WILDFIRE.TRACT_GAPS WHERE N_POLICIES >= 60 ORDER BY PREMIUM_GAP_PCT DESC FETCH FIRST 20 ROWS ONLY;
